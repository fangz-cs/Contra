"""Which prompts count as the request the reviewer judges the diff against.

The failure this pins down: during an evaluation run a background-task
notification arrived as a prompt, was recorded as the change request, and the
reviewer spent a whole cell asking whether the diff was underdetermined with
respect to `<task-notification>... exit code 144`. Filtering on `source` alone
did not catch it.
"""
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "hooks"))
import record_baseline as rb  # noqa: E402


@pytest.mark.parametrize("source,text", [
    ("user", "Accept-Encoding 里加上 br 支持"),
    ("sdk", "optimizations"),
    (None, "refactor the parser"),
])
def test_person_written_requests_are_kept(source, text):
    assert rb.authored({"source": source}, text)


@pytest.mark.parametrize("source,text", [
    (None, "<task-notification>\n<task-id>test-task</task-id>"),
    ("user", "<system-reminder>As you answer the user's questions"),
    ("user", "Caveat: The messages below were generated by the user"),
    ("user", "<local-command-stdout>done</local-command-stdout>"),
    ("loop_wakeup", "继续"),
    ("schedule_wakeup", "check the build"),
])
def test_harness_messages_are_rejected(source, text):
    assert not rb.authored({"source": source}, text)
