"""Score a protocol run the way the benchmark's own results table reports it.

``scripts/compute_metrics.py`` emits TKQR, ORA, turns and diff. The table this campaign
has to be comparable with (paper Table 2) also reports KQR and full-coverage broken out
by K, and puts confidence intervals on them that are bootstrapped over the 80 source
problems rather than the 419 tasks -- tasks derived from one source share a statement, so
resampling tasks independently would understate the interval.

Everything metric-defining is imported from the benchmark package. Only the columns it
does not expose are computed here, from the definitions in the paper:

    KQR           = (distinct key questions covered) / K
    full coverage = fraction of tasks with KQR == 1, reported per K
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from collections import defaultdict
from pathlib import Path

# Policies that consume a model-bound candidate pool. Ask-or-assume / bare do not.
FORKCAST_POOL_POLICIES = {"certified", "elicited", "rite"}


def parse_run_stem(stem: str) -> tuple[str, str, str]:
    """Split ``<policy>__<backbone>[__<split>]`` without breaking ``ask_or_assume``."""
    parts = stem.split("__")
    policy = parts[0]
    if len(parts) == 1:
        return policy, "", "underspecified"
    if parts[-1] in {"complete", "underspecified", "underspec"}:
        split = "complete" if parts[-1] == "complete" else "underspecified"
        backbone = "__".join(parts[1:-1]) if len(parts) > 2 else parts[1]
        return policy, backbone, split
    return policy, "__".join(parts[1:]), "underspecified"


def load(path: Path) -> list[dict]:
    """First finished record per task_id.

    Aligned with ``dprime_ci.py`` and ``final_table.sh``. Lane-4 durable scoring
    also computes the latest finished record and reports if they ever diverge.
    Unfinished resume/redo rows are audit-only and never enter the denominator.
    """
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            r = json.loads(line)
            if r.get("finished") and r.get("key_question_num") is not None:
                rows.append(r)
    seen, out = set(), []
    for r in rows:  # a resumed run can append a task twice; keep the first
        if r["task_id"] not in seen:
            seen.add(r["task_id"])
            out.append(r)
    return out


def load_latest(path: Path) -> tuple[list[dict], int]:
    """Latest finished record per task_id. Returns (rows, n_superseded)."""
    latest: dict[str, dict] = {}
    superseded = 0
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        r = json.loads(line)
        if not (r.get("finished") and r.get("key_question_num") is not None):
            continue
        tid = r["task_id"]
        if tid in latest:
            superseded += 1
        latest[tid] = r
    return list(latest.values()), superseded


def validate_pool_provenance(path: Path, rows: list[dict]) -> None:
    """Refuse cross-model ForkCast rows even when a caller names them explicitly."""
    policy, backbone, split = parse_run_stem(path.stem)
    if policy not in FORKCAST_POOL_POLICIES or not rows or not backbone:
        return
    bad = [
        row.get("task_id")
        for row in rows
        if (
            row.get("candidate_pool_model") != backbone
            or row.get("candidate_pool_split") != split
            or row.get("render_model") != backbone
            or not row.get("candidate_pool_sha256")
        )
    ]
    # The original gpt-5-mini rows predate provenance fields, but are valid because
    # text.json and the renderer were both generated by gpt-5-mini. Every new run,
    # and every non-gpt-5-mini run, must carry the fail-closed metadata.
    if bad and backbone == "gpt-5-mini" and len(bad) == len(rows):
        return
    if bad:
        raise SystemExit(
            f"REFUSING TO SCORE {path}: {len(bad)}/{len(rows)} finished rows "
            f"lack matching pool_model={backbone!r}, pool_split={split!r}, "
            f"renderer and pool SHA; first={bad[:5]}"
        )


def per_task(rec: dict, m) -> dict:
    K = m.key_question_num(rec)
    hits = sum(int(v) for v in (rec.get("hit_dict") or {}).values())
    s = m.score_record(rec)
    return {"task_id": rec["task_id"], "source": rec.get("id"), "K": K, "hits": hits,
            "kqr": hits / K if K else 0.0, "full": float(K > 0 and hits == K),
            "tkqr": s["tkqr"], "ora": s["ora"], "turns": s["turns"],
            "asked": float(s["turns"] > 0),
            "n_forks": rec.get("n_forks_available"),
            "template": sum(1 for a in (rec.get("asked_questions") or [])
                            if a.get("render") == "template"),
            "n_questions": len(rec.get("asked_questions") or [])}


def summarise(ts: list[dict]) -> dict:
    n = len(ts)
    if not n:
        return {}
    macro = lambda k: sum(t[k] for t in ts) / n  # noqa: E731
    return {"n": n,
            "KQR": sum(t["hits"] for t in ts) / max(1, sum(t["K"] for t in ts)),
            "KQR_macro": macro("kqr"), "TKQR": macro("tkqr"), "ORA": macro("ora"),
            "turns": macro("turns"), "full": macro("full"), "ask_rate": macro("asked")}


def boot_ci(ts: list[dict], stat, n_boot: int = 2000, seed: int = 20260802) -> tuple:
    """Percentile CI, resampling the source problems rather than the tasks."""
    by_source = defaultdict(list)
    for t in ts:
        by_source[t["source"]].append(t)
    sources = list(by_source)
    rng = random.Random(seed)
    vals = []
    for _ in range(n_boot):
        draw = []
        for _ in sources:
            draw.extend(by_source[sources[rng.randrange(len(sources))]])
        v = stat(draw)
        if v is not None:
            vals.append(v)
    if not vals:
        return (float("nan"), float("nan"))
    vals.sort()
    return vals[int(0.025 * len(vals))], vals[int(0.975 * len(vals))]


def paired_delta(a: list[dict], b: list[dict], key: str, n_boot: int = 2000) -> str:
    """Difference between two policies on the tasks both completed, clustered by source."""
    ib = {t["task_id"]: t for t in b}
    pairs = [(t, ib[t["task_id"]]) for t in a if t["task_id"] in ib]
    if not pairs:
        return "no overlap"
    num = lambda ps, i: (sum(p[i]["hits"] for p in ps) / max(1, sum(p[i]["K"] for p in ps))  # noqa: E731
                         if key == "KQR" else sum(p[i][key] for p in ps) / len(ps))
    obs = num(pairs, 0) - num(pairs, 1)
    by_source = defaultdict(list)
    for p in pairs:
        by_source[p[0]["source"]].append(p)
    sources = list(by_source)
    rng = random.Random(20260802)
    diffs = []
    for _ in range(n_boot):
        draw = []
        for _ in sources:
            draw.extend(by_source[sources[rng.randrange(len(sources))]])
        diffs.append(num(draw, 0) - num(draw, 1))
    diffs.sort()
    lo, hi = diffs[int(0.025 * n_boot)], diffs[int(0.975 * n_boot)]
    p = min(1.0, 2 * min(sum(d <= 0 for d in diffs), sum(d >= 0 for d in diffs)) / n_boot)
    star = "***" if p < 0.001 else "**" if p < 0.01 else "*" if p < 0.05 else "ns"
    return f"{obs:+.4f}  [{lo:+.4f}, {hi:+.4f}]  p={p:.4f} {star}  (n={len(pairs)})"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("runs", nargs="+", help="protocol run JSONL files")
    ap.add_argument(
        "--release",
        required=True,
        help="external directory containing the clarifycodebench package",
    )
    ap.add_argument("--boot", type=int, default=2000)
    ap.add_argument("--json", help="also write the summary here")
    args = ap.parse_args()

    sys.path.insert(0, args.release)
    from clarifycodebench import metrics as m

    runs = {}
    seen_stems = {}
    for p in map(Path, args.runs):
        # Two paths sharing a basename (e.g. a live run and a quarantined copy under
        # protocol_runs/parked/) would collapse onto one key and the last one would
        # silently win. Refuse instead of guessing which was intended.
        if p.stem in seen_stems:
            raise SystemExit(
                f"duplicate run name {p.stem!r}:\n  {seen_stems[p.stem]}\n  {p}\n"
                "Pass only one; scoring quarantined and live records together is "
                "never what you want.")
        seen_stems[p.stem] = p
        rows = load(p)
        if rows:
            validate_pool_provenance(p, rows)
            runs[p.stem] = [per_task(r, m) for r in rows]

    print(f"{'run':34} {'n':>4} {'KQR':>7} {'TKQR':>7} {'ORA':>6} {'turns':>6} "
          f"{'full%':>6} {'ask%':>6}")
    out = {}
    for name, ts in runs.items():
        s = summarise(ts)
        lo, hi = boot_ci(ts, lambda d: (sum(t["hits"] for t in d) /
                                        max(1, sum(t["K"] for t in d))), args.boot)
        print(f"{name:34} {s['n']:>4} {s['KQR']:>7.3f} {s['TKQR']:>7.3f} {s['ORA']:>6.3f} "
              f"{s['turns']:>6.2f} {s['full']:>6.1%} {s['ask_rate']:>6.1%}")
        print(f"{'':34} {'':>4} KQR 95% CI [{lo:.3f}, {hi:.3f}] (clustered on sources)")
        s["KQR_ci"] = [lo, hi]
        s["full_by_K"] = {}
        for K in (1, 2, 3):
            sub = [t for t in ts if t["K"] == K]
            if sub:
                fk = sum(t["full"] for t in sub) / len(sub)
                s["full_by_K"][K] = fk
                print(f"{'':34} {'':>4} full coverage K={K}: {fk:>6.1%}  (n={len(sub)})")
        q = sum(t["n_questions"] for t in ts)
        if q:
            tmpl = sum(t["template"] for t in ts)
            s["template_rate"] = tmpl / q
            print(f"{'':34} {'':>4} questions={q}  template fallback {tmpl}/{q} "
                  f"= {tmpl / q:.1%}")
        out[name] = s
        print()

    # A paired difference only means something within one cohort (backbone x split).
    # Run stems are "<policy>__<backbone>[__<split>]", so everything after the policy
    # is the cohort. Keying on the policy alone made a second backbone silently
    # overwrite the first and reported one cohort's numbers as if they covered both.
    cohorts = defaultdict(dict)
    for stem, ts in runs.items():
        policy, _sep, cohort = stem.partition("__")
        cohorts[cohort or "(unnamed)"][policy] = ts

    header_done = False
    for cohort in sorted(cohorts):
        keyed = cohorts[cohort]
        pairs = [(a, b) for a, b in (("certified", "bare"), ("elicited", "bare"),
                                     ("certified", "elicited"))
                 if a in keyed and b in keyed]
        if not pairs:
            missing = sorted({"bare", "elicited", "certified"} - set(keyed))
            print(f"PAIRED DIFFERENCES [{cohort}]: skipped, only {sorted(keyed)} "
                  f"present (missing {missing})\n")
            continue
        if not header_done:
            print("PAIRED DIFFERENCES (clustered bootstrap on source problems)")
            header_done = True
        print(f"  --- {cohort} ---")
        for a, b in pairs:
            for key in ("KQR", "tkqr", "full", "ora"):
                print(f"  {a} - {b:10} {key:5} {paired_delta(keyed[a], keyed[b], key, args.boot)}")
            print()

    if args.json:
        Path(args.json).write_text(json.dumps(out, indent=2))


if __name__ == "__main__":
    main()
